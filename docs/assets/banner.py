#!/usr/bin/env python3
"""Draw the README banner from the mascot in src/logo.rs, so the art stays in sync with the terminal.

    python3 docs/assets/banner.py                 # writes docs/assets/banner.svg
    python3 docs/assets/banner.py social.svg 640  # a 1280x640 social preview, for Settings > Social preview
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "banner.svg"

W = 1280
H = int(sys.argv[2]) if len(sys.argv) > 2 else 400
OUT = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else OUT
PX = 13  # size of one mascot pixel
FONT = "ui-monospace, SFMono-Regular, 'JetBrains Mono', Menlo, Consolas, 'Liberation Mono', monospace"


def rust_colors():
    """Named `Color::Rgb` constants in logo.rs and theme.rs, as hex."""
    named = {}
    for name in ("src/logo.rs", "src/theme.rs"):
        for m in re.finditer(r"const (\w+): Color = Color::Rgb\((\d+), (\d+), (\d+)\)", (ROOT / name).read_text()):
            named[m[1]] = "#%02x%02x%02x" % tuple(map(int, m.groups()[1:]))
    return named


def sprite():
    """The SPRITE rows and the color of each letter, read from `pixel` in logo.rs."""
    src = (ROOT / "src/logo.rs").read_text()
    rows = re.findall(r'"([.A-Za-z]+)"', src[src.index("const SPRITE") : src.index("];", src.index("const SPRITE"))])
    named = rust_colors()
    colors = {}
    body = src[src.index("fn pixel") : src.index("_ => return None")]
    for m in re.finditer(r"'(\w)' => (Color::Rgb\([^)]*\)|[\w:]+),", body):
        value = m[2].strip()
        rgb = re.fullmatch(r"Color::Rgb\((\d+), (\d+), (\d+)\)", value)
        colors[m[1]] = "#%02x%02x%02x" % tuple(map(int, rgb.groups())) if rgb else named[value.split("::")[-1]]
    return rows, colors


def sparkle(x, y, r, color, delay):
    """A four-pointed star that twinkles."""
    d = f"M{x},{y - r} Q{x},{y} {x + r},{y} Q{x},{y} {x},{y + r} Q{x},{y} {x - r},{y} Q{x},{y} {x},{y - r}Z"
    return f'<path class="tw" style="animation-delay:{delay}s" d="{d}" fill="{color}"/>'


def main():
    dy = (H - 400) // 2
    rows, colors = sprite()
    ox, oy = 110, (H - len(rows) * PX) // 2
    pixels = []
    for j, row in enumerate(rows):
        for i, c in enumerate(row):
            if c in colors:
                cls = ' class="glow"' if c in "OY" and j < 4 else ""
                pixels.append(f'<rect{cls} x="{ox + i * PX}" y="{oy + j * PX}" width="{PX}" height="{PX}" fill="{colors[c]}"/>')

    ember = rust_colors()["EMBER"]
    tx = ox + len(rows[0]) * PX + 70
    sparkles = [
        sparkle(70, 70 + dy, 10, "#ffd682", 0), sparkle(470, 60 + dy, 7, "#8cc4ff", 1.1), sparkle(1180, 80 + dy, 12, "#ff85c0", 0.5),
        sparkle(1210, 320 + dy, 8, "#ffd682", 1.7), sparkle(420, 345 + dy, 9, "#ff85c0", 2.3), sparkle(860, 350 + dy, 6, "#8cc4ff", 0.8),
        sparkle(60, 300 + dy, 6, "#c4a2ff", 1.4),
    ]
    chips, cx = [], tx
    for label, color in [("Rust", "#ffd682"), ("/fix", "#7adeb2"), ("MCP", "#8cc4ff"), ("Nemotron", "#c4a2ff")]:
        w = 26 + 15 * len(label)
        chips.append(
            f'<rect x="{cx}" y="{268 + dy}" width="{w}" height="40" rx="20" fill="{color}" fill-opacity="0.16" stroke="{color}" stroke-opacity="0.55"/>'
            f'<text x="{cx + w / 2}" y="{295 + dy}" text-anchor="middle" font-size="20" fill="{color}">{label}</text>'
        )
        cx += w + 14

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="ember: a terminal coding agent for NVIDIA Nemotron">
<!-- Generated by docs/assets/banner.py from the mascot in src/logo.rs. -->
<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#1c1430"/><stop offset="1" stop-color="#2d1f4d"/></linearGradient>
  <linearGradient id="word" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#ff85c0"/><stop offset="1" stop-color="{ember}"/></linearGradient>
  <radialGradient id="halo"><stop offset="0" stop-color="#b080e8" stop-opacity="0.35"/><stop offset="1" stop-color="#b080e8" stop-opacity="0"/></radialGradient>
</defs>
<style>
  .tw {{ animation: tw 3s ease-in-out infinite; transform-box: fill-box; transform-origin: center; }}
  .glow {{ animation: glow 2.4s ease-in-out infinite; }}
  @keyframes tw {{ 0%, 100% {{ opacity: 0.25; transform: scale(0.7); }} 50% {{ opacity: 1; transform: scale(1); }} }}
  @keyframes glow {{ 0%, 100% {{ opacity: 1; }} 50% {{ opacity: 0.55; }} }}
  @media (prefers-reduced-motion: reduce) {{ .tw, .glow {{ animation: none; }} }}
</style>
<rect width="{W}" height="{H}" rx="{28 if H == 400 else 0}" fill="url(#bg)"/>
<circle cx="{ox + len(rows[0]) * PX / 2}" cy="{H / 2}" r="230" fill="url(#halo)"/>
{chr(10).join(sparkles)}
<g shape-rendering="crispEdges">
{chr(10).join(pixels)}
</g>
<g font-family="{FONT}">
  <text x="{tx}" y="{178 + dy}" font-size="118" font-weight="700" fill="url(#word)" letter-spacing="-2">ember</text>
  <text x="{tx}" y="{232 + dy}" font-size="27" fill="#e6dcff">a terminal coding agent for NVIDIA Nemotron</text>
  {"".join(chips)}
</g>
</svg>
"""
    OUT.write_text(svg)
    print(f"wrote {OUT} ({len(pixels)} pixels)")


if __name__ == "__main__":
    main()
